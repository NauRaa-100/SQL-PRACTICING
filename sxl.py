#37. Find orders whose total value is 
# greater than the average order value.

'''
WITH order_totals AS (
    SELECT
        o.order_id,
        SUM(
            oi.quantity * oi.unit_price *
            (1 - COALESCE(oi.discount_pct, 0)/100.0)
        ) AS total_order_value
    FROM orders o
    JOIN order_items oi
        ON o.order_id = oi.order_id
    WHERE o.status = 'Completed'
    GROUP BY o.order_id
),
orders_with_average AS (
    SELECT
        order_id,
        total_order_value,
        AVG(total_order_value) OVER () AS average_order_value
    FROM order_totals
)
SELECT
    order_id,
    total_order_value,
    average_order_value
FROM orders_with_average
WHERE total_order_value > average_order_value
'''

