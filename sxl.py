#34. Find the top 3 products 
#by revenue within each category.

'''
WITH product_revenue AS (
    SELECT
        c.category_id,
        c.category_name,
        p.product_id,
        p.product_name,
        SUM(
            oi.quantity * oi.unit_price *
            (1 - COALESCE(oi.discount_pct, 0)/100.0)
        ) AS total_revenue
    FROM categories c
    JOIN products p
        ON c.category_id = p.category_id
    JOIN order_items oi
        ON p.product_id = oi.product_id
    JOIN orders o
        ON oi.order_id = o.order_id
    WHERE o.status = 'Completed'
    GROUP BY
        c.category_id,
        c.category_name,
        p.product_id,
        p.product_name
),
ranked_products AS (
    SELECT
        *,
        DENSE_RANK() OVER (
            PARTITION BY category_id
            ORDER BY total_revenue DESC
        ) AS product_rank
    FROM product_revenue
)
SELECT *
FROM ranked_products
WHERE product_rank <= 3
ORDER BY category_id, product_rank
'''

